#requires -Version 7.4
<#
.SYNOPSIS
    KbIntelligence extractor signature contract (shared engine).

.DESCRIPTION
    Canonical version source: EXTRACTOR_SIGNATURE_VERSION in Build-KbIntelligenceIndex.py.
    Hash: SHA-256 of a manifest of every module that shapes the index, in this fixed order:
    Build-KbIntelligenceIndex.py, GeneXusKbIntelligenceCore.py, GeneXusObjectTypeCatalogCore.py,
    GeneXusTransactionWritabilityCore.py (EXTRACTOR_SIGNATURE_MODULES in the build script, which
    must list the same files in the same order). The manifest has one line
    '<SHA-256 of the file's bytes> <file name>', LF-ended, per module, encoded as UTF-8 without a
    BOM; the files are read from this script's folder in the active repository, and the folder
    path is not part of the hash. compute_extractor_signature_hash in the build script computes
    the same value.
    Indexes without extractor_signature_* in the metadata are treated as generated by an old engine.
#>

Set-StrictMode -Version Latest

function Get-GeneXusKbIntelligenceExtractorSignatureModules {
    # Fixed order; EXTRACTOR_SIGNATURE_MODULES in Build-KbIntelligenceIndex.py lists the same files.
    return @(
        'Build-KbIntelligenceIndex.py',
        'GeneXusKbIntelligenceCore.py',
        'GeneXusObjectTypeCatalogCore.py',
        'GeneXusTransactionWritabilityCore.py'
    )
}

function Get-GeneXusKbIntelligenceExtractorScriptPath {
    return (Join-Path $PSScriptRoot 'Build-KbIntelligenceIndex.py')
}

function Get-GeneXusKbIntelligenceExtractorSignatureVersionFromSource {
    $scriptPath = Get-GeneXusKbIntelligenceExtractorScriptPath
    if (-not (Test-Path -LiteralPath $scriptPath -PathType Leaf)) {
        throw "Build-KbIntelligenceIndex.py not found: $scriptPath"
    }

    $content = [System.IO.File]::ReadAllText($scriptPath)
    $match = [regex]::Match(
        $content,
        'EXTRACTOR_SIGNATURE_VERSION\s*=\s*"(?<version>[^"]+)"'
    )
    if (-not $match.Success) {
        throw 'EXTRACTOR_SIGNATURE_VERSION missing in Build-KbIntelligenceIndex.py'
    }

    return $match.Groups['version'].Value
}

function ConvertTo-GeneXusKbIntelligenceSha256Hex {
    param([Parameter(Mandatory = $true)][AllowEmptyCollection()][byte[]]$Bytes)

    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    try {
        return (-join ($sha256.ComputeHash($Bytes) | ForEach-Object { $_.ToString('x2') }))
    }
    finally {
        $sha256.Dispose()
    }
}

function Get-GeneXusKbIntelligenceExpectedExtractorSignature {
    $manifest = New-Object System.Text.StringBuilder
    foreach ($moduleName in (Get-GeneXusKbIntelligenceExtractorSignatureModules)) {
        $modulePath = Join-Path $PSScriptRoot $moduleName
        if (-not (Test-Path -LiteralPath $modulePath -PathType Leaf)) {
            throw "Extractor signature module not found: $modulePath"
        }
        $moduleHash = ConvertTo-GeneXusKbIntelligenceSha256Hex -Bytes ([System.IO.File]::ReadAllBytes($modulePath))
        [void]$manifest.Append(('{0} {1}' -f $moduleHash, $moduleName)).Append([char]10)
    }
    $manifestBytes = (New-Object System.Text.UTF8Encoding($false)).GetBytes($manifest.ToString())

    return [ordered]@{
        extractor_signature_version = (Get-GeneXusKbIntelligenceExtractorSignatureVersionFromSource)
        extractor_signature_hash    = (ConvertTo-GeneXusKbIntelligenceSha256Hex -Bytes $manifestBytes)
    }
}

function Test-GeneXusKbIntelligenceExtractorSignatureFromMetadata {
    param(
        [Parameter(Mandatory = $true)]
        [hashtable]$Metadata
    )

    $expected = Get-GeneXusKbIntelligenceExpectedExtractorSignature
    $storedVersion = $Metadata['extractor_signature_version']
    $storedHash = $Metadata['extractor_signature_hash']

    if ([string]::IsNullOrWhiteSpace($storedVersion) -or [string]::IsNullOrWhiteSpace($storedHash)) {
        return [ordered]@{
            ok      = $false
            reason  = 'indice_sem_assinatura_extrator'
            summary = 'Index generated by an old engine (metadata without extractor_signature_version/hash) — regenerate with the current Build-KbIntelligenceIndex.py.'
            expected = $expected
            stored   = [ordered]@{
                extractor_signature_version = $storedVersion
                extractor_signature_hash    = $storedHash
            }
        }
    }

    if ($storedVersion -ne $expected.extractor_signature_version) {
        return [ordered]@{
            ok      = $false
            reason  = 'extrator_version_defasada'
            summary = ('Stale extractor signature (indexed version {0}, current engine {1}) — regenerate the index.' -f $storedVersion, $expected.extractor_signature_version)
            expected = $expected
            stored   = [ordered]@{
                extractor_signature_version = $storedVersion
                extractor_signature_hash    = $storedHash
            }
        }
    }

    if ($storedHash -ne $expected.extractor_signature_hash) {
        return [ordered]@{
            ok      = $false
            reason  = 'extrator_hash_defasado'
            summary = 'Index generated by an extractor build different from the current shared engine — regenerate the index.'
            expected = $expected
            stored   = [ordered]@{
                extractor_signature_version = $storedVersion
                extractor_signature_hash    = $storedHash
            }
        }
    }

    return [ordered]@{
        ok      = $true
        reason  = $null
        summary = $null
        expected = $expected
        stored   = [ordered]@{
            extractor_signature_version = $storedVersion
            extractor_signature_hash    = $storedHash
        }
    }
}

function Get-GeneXusKbIntelligenceExtractorSignatureFromIndexMetadataText {
    param(
        [Parameter(Mandatory = $true)]
        [string]$IndexMetadataText
    )

    $metadata = @{}
    foreach ($line in ($IndexMetadataText -split "(`r`n|`n|`r)")) {
        if ($line -match '^(?<key>[A-Za-z0-9_]+)\s*:\s*(?<value>.+)$') {
            $metadata[$Matches.key] = $Matches.value.Trim()
        }
    }

    return $metadata
}
